"""Веб-сервер Image Hunter — подключаемый и полностью удаляемый модуль (v0.8.0).

Модуль даёт доступ к программе с другого устройства — например, с телефона
в той же сети: маленький HTTP-сервер + внутреннее API + мобильный веб-
интерфейс. По возможностям повторяет основные действия программы: просмотр
папок и миниатюр, поиск по имени, поиск картинок в интернете со скачиванием,
полный просмотр, переименование, удаление в корзину, удаление фона (rembg),
журнал.

Устройство (каждая часть — отдельный файл, вместе — один пакет):

* ``api.py``   — внутреннее API: чистые функции над файловой системой без
  Qt-виджетов. Использует те же правила и кэш, что и сама программа:
  тот же кэш миниатюр на диске, те же правила переименования, тот же
  формат «*_nobg.png» у rembg;
* ``websearch.py`` — поиск картинок в интернете без браузера
  (DuckDuckGo JSON-выдача, Bing HTML) и скачивание по ссылкам с той же
  лестницей Referer и теми же правилами имён, что у загрузчика программы;
* ``httpd.py`` — маленький HTTP-сервер на stdlib (ThreadingHTTPServer):
  маршруты API, токен доступа, докачка Range для больших картинок;
* ``webui.py`` — мобильный веб-интерфейс одной HTML-страницей (без CDN —
  работает в локальной сети без интернета);
* ``manager.py`` — жизнь сервера из интерфейса программы: запуск/остановка,
  настройки, адреса машины в сети, журнал;
* ``dialog.py`` — окно настроек с QR-кодом для телефона.

Модуль полностью удаляемый: папка ``app/server/`` + кнопка «🌐» в
статус-баре (две строки в ``main_window.py``). Без запуска сервер не
создаёт ни потоков, ни соединений — нулевая цена, если он не нужен.

Доступ защищён токеном: он обязателен в адресе (``?token=…``), после
первого захода запоминается cookie. По умолчанию сервер слушает все
интерфейсы (чтобы телефон мог подключиться), но без токена не отдаёт
ничего. Режим «только просмотр» запрещает переименование, удаление и
удаление фона удалённо.
"""
