"""Мост «работа модулей → строка статуса» (v0.8.20).

Пожелание: «сделай, чтобы можно было видеть в строке статуса процесс
и/или статус работы модулей, особенно модуля удаления ватермарков».

Проблема: у модулей (rembg, водяные знаки) уже были сообщения в
статусной строке, но жили они в подписи вьюера (`local.status`) — её
затирает любое другое событие вьюера (открытие папки, поиск), а между
событиями задача может молчать минутами: грузятся модели, качается
Florence-2 (~0,5 ГБ при первом запуске), работает pip — и всё это без
единого обновления, выглядит как «программа зависла».

Как: каждый источник активности пишет сюда пары (текст, доля готовности).
Мост — Qt-сигналы, как у applog: подписывается виджет в статус-баре
(`app/ui/modstatus.py`), он держит активность НА ПОСТОЯННОМ месте справа,
рядом с подписью вьюера, и её не затирает ничего; когда доля неизвестна,
виджет сам тикает секундами («… · 45 с») — видно и процесс, и жив ли он.

Здесь только мост; тексты (i18n) — у вьюера, который этими задачами
распоряжается. Ключ модуля («wm», «rembg») — чтобы виджет мог отличить
одновременно идущие задачи: показывается последняя обновлённая.
"""

from __future__ import annotations

from PySide6.QtCore import QObject, Signal


class _Bridge(QObject):
    """Сигналы активности модулей; объект живёт в GUI-потоке."""

    activity = Signal(str, str, float)   # ключ модуля, текст, доля 0..1 или -1
    finished = Signal(str)               # ключ модуля — работа закончилась


bridge = _Bridge()


def report(key: str, text: str, frac: float = -1.0) -> None:
    """Сообщить о ходе работы модуля ``key``: текст и доля готовности.

    ``frac`` — доля 0..1 для полосы прогресса; когда посчитать нельзя
    (грузятся модели, идёт pip) — оставьте -1: виджет покажет текст
    и тикать секундами. Вызывается из GUI-потока (обработчики сигналов
    задач), из рабочих потоков — только через сигналы задач.
    """
    bridge.activity.emit(key, text, float(frac))


def done(key: str) -> None:
    """Модуль ``key`` закончил: активность снята с постоянного места.

    Итог при этом остаётся в обычных каналах — подписи вьюера и журнале.
    """
    bridge.finished.emit(key)
